import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { expect, test, type Page } from "@playwright/test";

/**
 * UI timings over the gold questions, through the real browser, API and model.
 * Opt-in (it costs about 20 cents): $env:MEASURE_UI = "1"; pnpm exec playwright test measure
 *
 * Per question, in a fresh page: time from pressing Enter to the first answer
 * text (or the refusal), and from clicking the first source (a citation chip,
 * or the closest passage of a refusal) to its highlight drawn on the PDF page
 * (the viewer's "citation-to-highlight" performance measure). Follow-ups are
 * left out: they need their conversation first. Writes evals/results/ui.json and .md.
 */
const GOLD = resolve(__dirname, "../../../evals/gold.jsonl");
const RESULTS = resolve(__dirname, "../../../evals/results");

type Gold = { id: string; question: string; history: string[] };
type Row = {
  id: string;
  outcome: "answered" | "refused";
  first_response_ms: number;
  click_to_highlight_ms: number;
};

test.skip(
  !process.env.MEASURE_UI,
  "set MEASURE_UI=1 to measure (calls the real model)",
);

test("measure first response and citation-to-highlight over the gold questions", async ({
  page,
  baseURL,
}) => {
  test.setTimeout(30 * 60_000);
  const items = readFileSync(GOLD, "utf8")
    .split("\n")
    .filter((line) => line.trim())
    .map((line) => JSON.parse(line) as Gold)
    .filter((item) => item.history.length === 0);
  const rows: Row[] = [];
  for (const item of items) {
    rows.push(await measure(page, item));
  }
  const summary = summarise(rows);
  writeFileSync(
    resolve(RESULTS, "ui.json"),
    JSON.stringify(
      {
        measured_at: new Date().toISOString(),
        base_url: baseURL,
        summary,
        rows,
      },
      null,
      2,
    ) + "\n",
  );
  writeFileSync(
    resolve(RESULTS, "ui.md"),
    markdown(summary, rows.length, baseURL ?? ""),
  );
  console.log(JSON.stringify(summary));
});

async function measure(page: Page, item: Gold): Promise<Row> {
  await page.goto("/", { waitUntil: "networkidle" });
  const box = page.getByLabel("Your question");
  await box.fill(item.question);
  const asked = Date.now();
  await box.press("Enter");
  const refused = page.getByText("Closest passages");
  await expect(page.locator(".prose-answer").or(refused).first()).toBeVisible({
    timeout: 90_000,
  });
  const firstResponse = Date.now() - asked;
  await expect(page.locator('article[aria-busy="true"]')).toHaveCount(0, {
    timeout: 90_000,
  });

  const outcome = (await refused.count()) ? "refused" : "answered";
  const source =
    outcome === "answered"
      ? page.getByRole("button", { name: /^Show source \d+$/ }).first()
      : refused.locator("..").getByRole("button").first();
  await page.evaluate(() => performance.clearMeasures("citation-to-highlight"));
  await source.click();
  await expect(page.locator("[data-highlight]").first()).toBeVisible({
    timeout: 60_000,
  });
  const ms = await page.waitForFunction(
    () =>
      performance.getEntriesByName("citation-to-highlight").at(-1)?.duration ??
      null,
    null,
    { timeout: 30_000 },
  );
  return {
    id: item.id,
    outcome,
    first_response_ms: firstResponse,
    click_to_highlight_ms: Math.round((await ms.jsonValue()) as number),
  };
}

function percentile(values: number[], q: number): number {
  const sorted = [...values].sort((a, b) => a - b);
  return (
    sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * q))] ?? 0
  );
}

function summarise(rows: Row[]) {
  const highlight = rows.map((r) => r.click_to_highlight_ms);
  const first = rows.map((r) => r.first_response_ms);
  return {
    questions: rows.length,
    answered: rows.filter((r) => r.outcome === "answered").length,
    click_to_highlight_ms_median: percentile(highlight, 0.5),
    click_to_highlight_ms_p95: percentile(highlight, 0.95),
    first_response_ms_median: percentile(first, 0.5),
    first_response_ms_p95: percentile(first, 0.95),
  };
}

function markdown(
  s: ReturnType<typeof summarise>,
  n: number,
  baseUrl: string,
): string {
  return [
    "# UI timings",
    "",
    `Generated by \`apps/web/e2e/measure.spec.ts\` against ${baseUrl}: ${n} gold questions ` +
      `without history (${s.answered} answered, the rest refused), each in a fresh page, ` +
      "Chromium on the dev machine. Click to highlight includes downloading and opening the PDF, " +
      "since each question starts in a new page.",
    "",
    "| measure | median ms | p95 ms |",
    "|---|---:|---:|",
    `| click on a source to its highlight on the page | ${s.click_to_highlight_ms_median} | ${s.click_to_highlight_ms_p95} |`,
    `| question to first answer text (or the refusal) | ${s.first_response_ms_median} | ${s.first_response_ms_p95} |`,
    "",
  ].join("\n");
}
